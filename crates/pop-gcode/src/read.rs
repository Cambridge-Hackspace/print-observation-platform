//! Reading the comment lines slicers write, as the file streams past.
//!
//! The slicers this reads, and where each puts what:
//!
//! - PrusaSlicer, SuperSlicer and OrcaSlicer write `; key = value` lines,
//!   mostly at the end: `printer_model`, `nozzle_diameter`, `filament_type`,
//!   `filament_colour`, `filament used [g]` and `[mm]`, `total filament used
//!   [g]`, `estimated printing time (normal mode)`. Per-filament values are
//!   lists: `;` between strings, `,` between numbers.
//! - Bambu Studio writes the same `key = value` settings, and a header of
//!   `; key: value` lines: `total estimated time`, `total filament weight
//!   [g]`, and `filament`, the slots used, from 1. It writes no grams or
//!   length per filament.
//! - Cura writes `;KEY:value`. Marlin flavor: `TIME` in seconds, `Filament
//!   used` in metres per extruder, `TARGET_MACHINE.NAME`. Griffin flavor
//!   (UltiMaker printers): `PRINT.TIME`, and per extruder train its nozzle and
//!   the material's volume used. Neither names the material or its weight.

use std::collections::BTreeMap;

use crate::{Filament, Metadata, Slicer, SlicerKind};

/// The longest comment line read. A longer one is skipped whole, so a file of
/// one endless line holds this much and no more. Real ones are far shorter:
/// PrusaSlicer's longest settings line is under 1 KiB.
pub const MAX_LINE: usize = 64 * 1024;

/// Reads metadata from G-code fed in pieces of any size. The pieces' sizes
/// never change what it reads.
#[derive(Debug, Default)]
pub struct Scanner {
    line: Vec<u8>,
    /// The current line outgrew [`MAX_LINE`]: skip to its end.
    skipping: bool,
    raw: Raw,
}

/// What the file said, as it said it. The last of a key wins.
#[derive(Debug, Default)]
struct Raw {
    generator: Option<String>,
    generator_version: Option<String>,
    printer_model: Option<String>,
    nozzles: Option<String>,
    materials: Option<String>,
    colors: Option<String>,
    grams: Option<String>,
    lengths_mm: Option<String>,
    total_grams: Option<String>,
    estimated_normal: Option<String>,
    // Bambu Studio's header.
    total_estimated: Option<String>,
    slots_used: Option<String>,
    // Cura's.
    cura_seconds: Option<String>,
    cura_print_seconds: Option<String>,
    cura_lengths_m: Option<String>,
    cura_nozzles: BTreeMap<usize, String>,
    cura_volumes_mm3: BTreeMap<usize, String>,
}

impl Scanner {
    pub fn new() -> Self {
        Self::default()
    }

    /// Read the next piece of the file.
    pub fn push(&mut self, mut piece: &[u8]) {
        while !piece.is_empty() {
            let (upto, rest, ended) = match piece.iter().position(|&b| b == b'\n') {
                Some(i) => (&piece[..i], &piece[i + 1..], true),
                None => (piece, &[][..], false),
            };
            piece = rest;
            if !self.skipping {
                if self.line.len() + upto.len() > MAX_LINE {
                    self.skipping = true;
                    self.line.clear();
                } else {
                    self.line.extend_from_slice(upto);
                }
            }
            if ended {
                self.end_line();
            }
        }
    }

    /// How many bytes of an unfinished line it holds: never more than
    /// [`MAX_LINE`].
    pub fn held(&self) -> usize {
        self.line.len()
    }

    /// The file has ended: what it said.
    pub fn finish(mut self) -> Metadata {
        self.end_line();
        self.raw.metadata()
    }

    fn end_line(&mut self) {
        let line = std::mem::take(&mut self.line);
        // A CRLF file's \r goes with the trimming of every value. A line that
        // is not UTF-8 is no slicer's.
        if !std::mem::take(&mut self.skipping)
            && let Ok(text) = std::str::from_utf8(&line)
        {
            self.raw.line(text);
        }
        self.line = line;
        self.line.clear();
    }
}

impl Raw {
    fn line(&mut self, line: &str) {
        let Some(body) = line.strip_prefix(';') else {
            return;
        };
        if let Some(rest) = body.strip_prefix(' ') {
            self.spaced(rest.trim());
        } else {
            self.cura(body.trim());
        }
    }

    /// `; ...`: PrusaSlicer, SuperSlicer, OrcaSlicer and Bambu Studio.
    fn spaced(&mut self, s: &str) {
        if let Some(rest) = s.strip_prefix("generated by ") {
            // "generated by PrusaSlicer 2.9.4 on 2026-11-26 at 23:07:14 UTC"
            let mut words = rest.split_whitespace();
            self.generator = words.next().map(str::to_owned);
            self.generator_version = words.next().filter(|v| *v != "on").map(str::to_owned);
            return;
        }
        if let Some(version) = s.strip_prefix("BambuStudio ") {
            // Bambu Studio's header: "; BambuStudio 02.09.01.70".
            if is_version(version) {
                self.generator = Some("BambuStudio".into());
                self.generator_version = Some(version.into());
            }
            return;
        }
        if let Some((key, value)) = s.split_once(" = ") {
            let value = Some(value.trim().to_owned());
            match key.trim() {
                "printer_model" => self.printer_model = value,
                "nozzle_diameter" => self.nozzles = value,
                "filament_type" => self.materials = value,
                "filament_colour" => self.colors = value,
                "filament used [g]" => self.grams = value,
                "filament used [mm]" => self.lengths_mm = value,
                "total filament used [g]" => self.total_grams = value,
                "estimated printing time (normal mode)" => self.estimated_normal = value,
                _ => {}
            }
            return;
        }
        // Bambu Studio's header: "; key: value", or several on one line
        // between semicolons ("; model printing time: 6m 31s; total
        // estimated time: 6m 50s").
        for part in s.split(';') {
            let Some((key, value)) = part.split_once(':') else {
                continue;
            };
            let value = Some(value.trim().to_owned());
            match key.trim() {
                "total estimated time" => self.total_estimated = value,
                "total filament weight [g]" => self.total_grams = value,
                "filament" => self.slots_used = value,
                _ => {}
            }
        }
    }

    /// `;KEY:value`: Cura.
    fn cura(&mut self, s: &str) {
        if let Some(version) = s.strip_prefix("Generated with Cura_SteamEngine ") {
            self.generator = Some("Cura_SteamEngine".into());
            self.generator_version = Some(version.trim().to_owned());
            return;
        }
        let Some((key, value)) = s.split_once(':') else {
            return;
        };
        let value = value.trim().to_owned();
        match key {
            "TIME" => self.cura_seconds = Some(value),
            "PRINT.TIME" => self.cura_print_seconds = Some(value),
            "Filament used" => self.cura_lengths_m = Some(value),
            "TARGET_MACHINE.NAME" => self.printer_model = Some(value),
            "GENERATOR.NAME" => self.generator = Some(value),
            "GENERATOR.VERSION" => self.generator_version = Some(value),
            _ => {
                let Some(train) = key.strip_prefix("EXTRUDER_TRAIN.") else {
                    return;
                };
                let Some((n, what)) = train.split_once('.') else {
                    return;
                };
                let Ok(n) = n.parse::<usize>() else {
                    return;
                };
                // A train number is an extruder's: a printer has a few. A
                // file claiming more is not one this reads.
                if n >= MAX_SLOTS {
                    return;
                }
                match what {
                    "NOZZLE.DIAMETER" => _ = self.cura_nozzles.insert(n, value),
                    "MATERIAL.VOLUME_USED" => _ = self.cura_volumes_mm3.insert(n, value),
                    _ => {}
                }
            }
        }
    }

    fn metadata(&self) -> Metadata {
        Metadata {
            slicer: self.generator.as_deref().map(|name| Slicer {
                kind: match name {
                    "PrusaSlicer" => SlicerKind::PrusaSlicer,
                    "SuperSlicer" => SlicerKind::SuperSlicer,
                    "OrcaSlicer" => SlicerKind::OrcaSlicer,
                    "BambuStudio" => SlicerKind::BambuStudio,
                    "Cura_SteamEngine" => SlicerKind::Cura,
                    other => SlicerKind::Other(other.to_owned()),
                },
                version: self.generator_version.clone().filter(|v| !v.is_empty()),
            }),
            printer_model: self.printer_model.as_deref().and_then(text),
            nozzles_mm: self.nozzles(),
            estimated_seconds: self.estimated_seconds(),
            filaments: self.filaments(),
            total_grams: self
                .total_grams
                .as_deref()
                .and_then(amount)
                .filter(|&g| g > 0.0),
        }
    }

    fn nozzles(&self) -> Vec<f64> {
        let listed: Vec<&str> = match &self.nozzles {
            Some(list) => list.split(',').collect(),
            None => {
                // Cura's trains, which must run 0, 1, ... with no gap.
                if !self
                    .cura_nozzles
                    .keys()
                    .copied()
                    .eq(0..self.cura_nozzles.len())
                {
                    return Vec::new();
                }
                self.cura_nozzles.values().map(String::as_str).collect()
            }
        };
        // One that does not read makes the list unreadable, rather than
        // shifting the rest onto the wrong extruders.
        listed
            .iter()
            .map(|n| amount(n).filter(|&d| d > 0.0))
            .collect::<Option<Vec<_>>>()
            .unwrap_or_default()
    }

    fn estimated_seconds(&self) -> Option<u64> {
        self.estimated_normal
            .as_deref()
            .and_then(duration)
            .or_else(|| self.total_estimated.as_deref().and_then(duration))
            .or_else(|| self.cura_print_seconds.as_deref().and_then(seconds))
            .or_else(|| self.cura_seconds.as_deref().and_then(seconds))
    }

    fn filaments(&self) -> Vec<Filament> {
        let materials = strings(self.materials.as_deref());
        let colors = strings(self.colors.as_deref());
        let grams = numbers(self.grams.as_deref(), "");
        let lengths = numbers(self.lengths_mm.as_deref(), "");
        let cura_lengths = numbers(self.cura_lengths_m.as_deref(), "m");
        let slots_used: Option<Vec<usize>> = self.slots_used.as_deref().map(|s| {
            s.split(',')
                .filter_map(|n| n.trim().parse::<usize>().ok())
                .filter(|&n| (1..=MAX_SLOTS).contains(&n))
                .map(|n| n - 1)
                .collect()
        });
        let volume = |slot: usize| self.cura_volumes_mm3.get(&slot).and_then(|v| amount(v));

        let slots = [
            materials.len(),
            colors.len(),
            grams.len(),
            lengths.len(),
            cura_lengths.len(),
            self.cura_volumes_mm3
                .keys()
                .next_back()
                .map_or(0, |&n| n + 1),
            slots_used
                .iter()
                .flatten()
                .map(|&n| n + 1)
                .max()
                .unwrap_or(0),
        ]
        .into_iter()
        .max()
        .unwrap_or(0)
        .min(MAX_SLOTS);

        // Whether a slot is used, by the first thing the file says about it.
        let used = |slot: usize| -> Option<bool> {
            if let Some(used) = &slots_used {
                return Some(used.contains(&slot));
            }
            [
                lengths.get(slot).copied().flatten(),
                grams.get(slot).copied().flatten(),
                cura_lengths.get(slot).copied().flatten(),
                volume(slot),
            ]
            .into_iter()
            .flatten()
            .next()
            .map(|n| n > 0.0)
        };
        let any_use_known = (0..slots).any(|s| used(s).is_some());

        (0..slots)
            .filter(|&s| {
                if any_use_known {
                    used(s) == Some(true)
                } else {
                    true
                }
            })
            .map(|slot| Filament {
                slot,
                material: materials.get(slot).cloned().flatten(),
                color: colors.get(slot).cloned().flatten().and_then(|c| color(&c)),
                // A used filament weighing 0 g is one whose density the
                // slicer did not know.
                grams: grams.get(slot).copied().flatten().filter(|&g| g > 0.0),
            })
            .collect()
    }
}

/// The most extruders or slots a file is read as having. Bambu's largest
/// arrangement is four AMS units of four.
const MAX_SLOTS: usize = 32;

fn is_version(s: &str) -> bool {
    !s.is_empty() && s.chars().all(|c| c.is_ascii_digit() || c == '.')
}

/// A string value: trimmed, unquoted, and missing when empty.
fn text(s: &str) -> Option<String> {
    let s = s.trim();
    let s = s
        .strip_prefix('"')
        .and_then(|s| s.strip_suffix('"'))
        .unwrap_or(s)
        .trim();
    (!s.is_empty()).then(|| s.to_owned())
}

/// A `;`-separated list of strings, each missing where it is empty.
fn strings(list: Option<&str>) -> Vec<Option<String>> {
    match list {
        Some(l) => l.split(';').map(text).collect(),
        None => Vec::new(),
    }
}

/// A `,`-separated list of numbers, each with `unit` after it, each missing
/// where it does not read.
fn numbers(list: Option<&str>, unit: &str) -> Vec<Option<f64>> {
    match list {
        Some(l) => l
            .split(',')
            .map(|n| amount(n.trim().strip_suffix(unit).unwrap_or(n.trim())))
            .collect(),
        None => Vec::new(),
    }
}

/// A quantity: finite and not negative.
fn amount(s: &str) -> Option<f64> {
    s.trim()
        .parse::<f64>()
        .ok()
        .filter(|n| n.is_finite() && *n >= 0.0)
}

/// Whole seconds, as Cura writes them.
fn seconds(s: &str) -> Option<u64> {
    s.trim().parse().ok()
}

/// "1d 2h 3m 4s", any of them left out, in that order.
fn duration(s: &str) -> Option<u64> {
    let mut total: u64 = 0;
    let mut last_unit = 0;
    let mut any = false;
    for word in s.split_whitespace() {
        let (n, unit) = word.split_at(word.len().checked_sub(1)?);
        let (rank, scale) = match unit {
            "d" => (1, 86_400),
            "h" => (2, 3_600),
            "m" => (3, 60),
            "s" => (4, 1),
            _ => return None,
        };
        if rank <= last_unit {
            return None;
        }
        last_unit = rank;
        let n: u64 = n.parse().ok()?;
        total = total.checked_add(n.checked_mul(scale)?)?;
        any = true;
    }
    any.then_some(total)
}

/// `#RRGGBB` or `#RRGGBBAA`, upper case.
fn color(s: &str) -> Option<String> {
    let hex = s.trim().strip_prefix('#')?;
    ((hex.len() == 6 || hex.len() == 8) && hex.chars().all(|c| c.is_ascii_hexdigit()))
        .then(|| format!("#{}", hex.to_ascii_uppercase()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_duration_reads_in_order_or_not_at_all() {
        assert_eq!(duration("6m 48s"), Some(408));
        assert_eq!(duration("1d 2h 3m 4s"), Some(93_784));
        assert_eq!(duration("45s"), Some(45));
        assert_eq!(duration("2h"), Some(7_200));
        for bad in [
            "",
            "6m 6m",
            "48s 6m",
            "6x",
            "m",
            "-1s",
            "1.5h",
            "99999999999999999999d",
        ] {
            assert_eq!(duration(bad), None, "{bad:?}");
        }
    }

    #[test]
    fn a_color_is_hex_or_missing() {
        assert_eq!(color("#ff8000").as_deref(), Some("#FF8000"));
        assert_eq!(color("#00AE42FF").as_deref(), Some("#00AE42FF"));
        for bad in ["", "#", "FF8000", "#FF800", "#GG8000", "red"] {
            assert_eq!(color(bad), None, "{bad:?}");
        }
    }

    #[test]
    fn an_amount_is_finite_and_not_negative() {
        assert_eq!(amount(" 2.21 "), Some(2.21));
        for bad in ["", "NaN", "inf", "-1", "2,21", "1e999"] {
            assert_eq!(amount(bad), None, "{bad:?}");
        }
    }
}
